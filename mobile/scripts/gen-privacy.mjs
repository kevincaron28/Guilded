// Builds mobile/src/privacyText.ts from docs/PRIVACY.md, so the privacy policy shown in the app (phone app 0.7.0) is the
// published one, word for word. Run after editing docs/PRIVACY.md:  node mobile/scripts/gen-privacy.mjs
// tests/mobile-privacy-text.test.ts fails when the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** The policy split by language (## English / ## Français) and by ### section; the text before the first ### is the intro. */
export function parsePrivacy(markdown) {
  const text = markdown.replace(/\r\n/g, "\n");
  const updated = (/^Last updated[^\n]*$/m.exec(text)?.[0] ?? "").trim();
  const lang = (heading) => {
    const start = text.indexOf(`\n## ${heading}\n`);
    if (start < 0) throw new Error(`docs/PRIVACY.md has no "## ${heading}" part`);
    const rest = text.slice(start + heading.length + 5);
    const end = rest.search(/\n## /);
    const body = (end < 0 ? rest : rest.slice(0, end)).trim();
    const parts = body.split(/\n(?=### )/);
    const intro = parts[0].startsWith("### ") ? "" : parts.shift().trim();
    return { intro, sections: parts.map((part) => { const [first, ...lines] = part.split("\n"); return { title: first.replace(/^###\s+/, "").trim(), body: lines.join("\n").trim() }; }) };
  };
  return { updated, en: lang("English"), fr: lang("Français") };
}

export function privacyModule(markdown) {
  return `// Generated by mobile/scripts/gen-privacy.mjs from docs/PRIVACY.md. Do not edit by hand.\n`
    + `export interface PrivacySection { title: string; body: string }\n`
    + `export interface PrivacyText { intro: string; sections: PrivacySection[] }\n`
    + `export const PRIVACY: { updated: string; en: PrivacyText; fr: PrivacyText } = ${JSON.stringify(parsePrivacy(markdown), null, 1)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "mobile", "src", "privacyText.ts"), privacyModule(readFileSync(join(root, "docs", "PRIVACY.md"), "utf8")));
  console.log("mobile/src/privacyText.ts written");
}
