import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/**
 * Painted backdrops for any card (the general form of dungeon-backdrop.ts). `backdropFor(kind, key, variant)` looks for an
 * approved picture in `site/card-art/<kind>/<key>.jpg` (or `.png`), darkens it so the card's text stays readable, and returns it as
 * a small JPEG. When no approved file exists (or it cannot be read) it returns null and the caller draws the card exactly as it
 * did before, so adding this changes nothing until art is added. Nothing in the folder is generated by the bot.
 *
 * Memory: only the finished JPEG (about 30-250 KB) is cached, never a decoded picture, and the cache is limited by BYTES
 * (BACKDROP_BUDGET_BYTES), not by entry count. Pictures are prepared one at a time, so at most one source picture is decoded
 * at once: sources are limited to 2500x1500 pixels (about 15 MB decoded, a few copies while sharp works); the 1200x630 working
 * image is about 3 MB.
 */
/** "full" is a two-column card with rows (opaque panel on the right); "wide" a card without rows, whose text can reach the right edge. */
export type BackdropVariant = "banner" | "full" | "wide";
export const BACKDROP_BUDGET_BYTES = 4 * 1024 * 1024;
/** A banner is the header band of a ladder card (it fades into the card at its foot); a full backdrop fills a 1200x630 card. */
export const BANNER_HEIGHT = 176;
const KIND = /^[a-z0-9-]{1,24}$/, KEY = /^[a-z0-9-]{1,40}$/;
const BG = { r: 0x12, g: 0x0d, b: 0x08 };
const MISS_TTL_MS = 10 * 60_000, MISS_MAX = 200;

/** Where the text sits on each variant (x, y, width, height), for the contrast check. */
const TEXT_REGIONS: Record<BackdropVariant, { left: number; top: number; width: number; height: number }[]> = {
  // The roster subtitle can run about 1000 px wide, so the header region spans the card.
  banner: [{ left: 56, top: 30, width: 1090, height: 136 }],
  full: [{ left: 52, top: 30, width: 530, height: 536 }, { left: 56, top: 584, width: 1090, height: 40 }],
  wide: [{ left: 52, top: 30, width: 1096, height: 536 }, { left: 56, top: 584, width: 1090, height: 40 }]
};
/** Muted parchment text (#b9a77f): relative luminance 0.394. The background must reach 4.5:1 against it. */
const MUTED_LUMINANCE = 0.394, TARGET_RATIO = 4.5;

const cache = new Map<string, Buffer>();
let cacheBytes = 0;
const misses = new Map<string, number>();
const pending = new Map<string, Promise<Buffer | null>>();
let queue: Promise<unknown> = Promise.resolve();

/** For tests and diagnostics: how many bytes of finished backdrops are held. */
export function backdropCacheBytes(): number { return cacheBytes; }
export function backdropCacheEntries(): number { return cache.size; }
/** Drops everything held (tests; a deploy restarts the process anyway). */
export function resetBackdropCache(): void { cache.clear(); misses.clear(); cacheBytes = 0; }

function remember(id: string, art: Buffer): void {
  const known = cache.get(id);
  if (known) { cacheBytes -= known.length; cache.delete(id); }
  // A picture bigger than the whole budget is used once and not kept.
  if (art.length > BACKDROP_BUDGET_BYTES) return;
  cache.set(id, art); cacheBytes += art.length;
  while (cacheBytes > BACKDROP_BUDGET_BYTES) {
    const oldest = cache.keys().next().value as string, dropped = cache.get(oldest)!;
    cache.delete(oldest); cacheBytes -= dropped.length;
  }
}

const channelLuminance = (value: number) => { const c = value / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
/** Estimated brightest typical background under a region: each channel's mean plus one standard deviation, as relative luminance. */
async function regionLuminance(image: Buffer, region: { left: number; top: number; width: number; height: number }): Promise<number> {
  const { channels } = await sharp(image).extract(region).stats();
  const [r, g, b] = [0, 1, 2].map(i => Math.min(255, channels[i]!.mean + channels[i]!.stdev));
  return 0.2126 * channelLuminance(r!) + 0.7152 * channelLuminance(g!) + 0.0722 * channelLuminance(b!);
}
/** Contrast of muted card text over the worst text region of `image` (pure measurement; exported for tests). */
export async function textContrast(image: Buffer, variant: BackdropVariant): Promise<number> {
  let worst = 0;
  for (const region of TEXT_REGIONS[variant]) worst = Math.max(worst, await regionLuminance(image, region));
  return (MUTED_LUMINANCE + 0.05) / (worst + 0.05);
}

async function prepare(file: string, variant: BackdropVariant): Promise<Buffer> {
  const source = await readFile(file);
  const height = variant === "banner" ? BANNER_HEIGHT : 630;
  // A transparent picture is laid on the card's own background first (not black).
  let base = sharp(source, { limitInputPixels: 2500 * 1500 }).flatten({ background: BG }).resize(1200, 630, { fit: "cover" });
  if (variant === "banner") base = sharp(await base.png().toBuffer()).extract({ left: 0, top: Math.round((630 - BANNER_HEIGHT) * 0.45), width: 1200, height: BANNER_HEIGHT });
  // The shade: dark under the left column (where the text is), lighter to the right; a banner also fades into the card's own
  // background at its foot so the panels below start on a flat colour.
  const stops = variant === "banner"
    ? `<stop offset="0" stop-color="#000" stop-opacity=".78"/><stop offset=".55" stop-color="#000" stop-opacity=".62"/><stop offset="1" stop-color="#000" stop-opacity=".38"/>`
    : `<stop offset="0" stop-color="#000" stop-opacity=".74"/><stop offset=".42" stop-color="#000" stop-opacity=".66"/><stop offset=".56" stop-color="#000" stop-opacity=".3"/><stop offset="1" stop-color="#000" stop-opacity=".25"/>`;
  const fade = variant === "banner"
    ? `<linearGradient id="f" x1="0" y1="0" x2="0" y2="1"><stop offset=".62" stop-color="#120d08" stop-opacity="0"/><stop offset="1" stop-color="#120d08" stop-opacity="1"/></linearGradient><rect width="1200" height="${height}" fill="url(#f)"/>`
    : `<linearGradient id="f" x1="0" y1="0" x2="0" y2="1"><stop offset=".88" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".55"/></linearGradient><rect width="1200" height="${height}" fill="url(#f)"/>`;
  const shade = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="${height}"><defs><linearGradient id="s" x1="0" y1="0" x2="1" y2="0">${stops}</linearGradient></defs><rect width="1200" height="${height}" fill="url(#s)"/>${fade}</svg>`);
  let image = await base.composite([{ input: shade }]).png().toBuffer();
  // Contrast guard: measured where text is drawn; darken in steps until muted text keeps 4.5:1 (never more than 10 steps).
  for (let step = 0; step < 10 && await textContrast(image, variant) < TARGET_RATIO; step++) {
    image = await sharp(image).linear(0.8, 0).png().toBuffer();
  }
  return sharp(image).jpeg({ quality: 86 }).toBuffer();
}

async function find(kind: string, key: string, variant: BackdropVariant): Promise<Buffer | null> {
  for (const extension of ["jpg", "png"]) {
    try { return await prepare(fileURLToPath(new URL(`../../site/card-art/${kind}/${key}.${extension}`, import.meta.url)), variant); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT" && extension === "png") return null; }
  }
  return null;
}

/**
 * The prepared backdrop (a JPEG, 1200 x 176 for a banner, 1200 x 630 for a full card) for an approved picture, or null when there
 * is none: unknown kind or key, no file, an unreadable file. Never throws.
 */
export async function backdropFor(kind: string, key: string, variant: BackdropVariant): Promise<Buffer | null> {
  if (!KIND.test(kind) || !KEY.test(key)) return null;
  const id = `${variant}/${kind}/${key}`, known = cache.get(id);
  if (known) { cache.delete(id); cache.set(id, known); return known; }
  const missed = misses.get(id);
  if (missed !== undefined && Date.now() - missed < MISS_TTL_MS) return null;
  let work = pending.get(id);
  if (!work) {
    // One picture at a time keeps the decoded copies to a single image.
    work = queue.then(() => find(kind, key, variant)).catch(() => null).then(art => {
      if (art) remember(id, art);
      else { misses.set(id, Date.now()); while (misses.size > MISS_MAX) misses.delete(misses.keys().next().value as string); }
      return art;
    });
    queue = work; pending.set(id, work);
    void work.finally(() => { if (pending.get(id) === work) pending.delete(id); });
  }
  return work;
}

/** Which approved picture a card asks for. Stored inside a queued card definition, so it must stay small and plain. */
export interface CardBackdrop { kind: string; key: string; /** Tried when `key` has no file. */ fallbackKey?: string | undefined }

/** The backdrop a card asks for, or null (no request, or no approved file for the key or its fallback). */
export async function cardBackdropArt(request: CardBackdrop | undefined, variant: BackdropVariant): Promise<Buffer | null> {
  if (!request) return null;
  return (await backdropFor(request.kind, request.key, variant)) ?? (request.fallbackKey ? await backdropFor(request.kind, request.fallbackKey, variant) : null);
}
