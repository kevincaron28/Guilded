const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("companion", {
  setLanguage: (language) => ipcRenderer.invoke("set-language", language),
  getAll: () => ipcRenderer.invoke("get-all"),
  listProfiles: () => ipcRenderer.invoke("list-profiles"),
  changeProfile: (choice) => ipcRenderer.invoke("change-profile", choice),
  saveConfig: (config) => ipcRenderer.invoke("save-config", config),
  testConnection: (config) => ipcRenderer.invoke("test-connection", config),
  pairAccount: (config) => ipcRenderer.invoke("pair-account", config),
  signInStart: (config) => ipcRenderer.invoke("sign-in-start", config),
  signInWait: () => ipcRenderer.invoke("sign-in-wait"),
  signInCancel: () => ipcRenderer.invoke("sign-in-cancel"),
  browseFile: () => ipcRenderer.invoke("browse-file"),
  browsePoeLog: () => ipcRenderer.invoke("browse-poe-log"),
  detectWow: () => ipcRenderer.invoke("detect-wow"),
  switchLiveFolder: () => ipcRenderer.invoke("switch-live-folder"),
  dismissLiveFolder: () => ipcRenderer.invoke("dismiss-live-folder"),
  uploadNow: () => ipcRenderer.invoke("upload-now"),
  refreshStandings: () => ipcRenderer.invoke("refresh-standings"),
  exportSheets: (table) => ipcRenderer.invoke("export-sheets", table),
  convertGRM: (options) => ipcRenderer.invoke("convert-grm", options),
  setAutostart: (on) => ipcRenderer.invoke("set-autostart", on),
  openAddonFolder: () => ipcRenderer.invoke("open-addon-folder"),
  removeData: () => ipcRenderer.invoke("remove-data"),
  toggleTracking: () => ipcRenderer.invoke("toggle-tracking"),
  getPoeRuns: () => ipcRenderer.invoke("get-poe-runs"),
  openOnline: () => ipcRenderer.invoke("open-online"),
  openUpdate: () => ipcRenderer.invoke("open-update"),
  installUpdate: () => ipcRenderer.invoke("install-update"),
  onUpdateProgress: (callback) => ipcRenderer.on("update-progress", (_event, percent) => callback(percent)),
  manageView: () => ipcRenderer.invoke("manage-view"),
  manageEdit: (change) => ipcRenderer.invoke("manage-edit", change),
  onState: (callback) => ipcRenderer.on("state", (_event, state) => callback(state)),
  onLog: (callback) => ipcRenderer.on("log", (_event, entry) => callback(entry))
});
