// Writes mobile/src/clash/set1.ts: the display data of Guilded Clash set 1 (name, cost, type, stats, text) from the
// bot's card data, so the phone can draw the ids a match sends. Rules stay on the server; the phone never needs them.
// Run from the repo root after the set changes: npx tsx mobile/scripts/gen-clash-cards.ts
import { writeFileSync } from "node:fs";
import { CARD_BY_ID, roleOfCard } from "../../src/services/tcg-cards-set1.js";
import { CARDS_SET1_FR } from "../../src/services/tcg-cards-set1-fr.js";

const rows = [...CARD_BY_ID.values()].map((card) => ({
  id: card.id, name: card.name, type: card.type, rarity: card.rarity, cost: card.cost, cls: card.cls,
  ...(card.atk !== undefined ? { atk: card.atk } : {}), ...(card.hp !== undefined ? { hp: card.hp } : {}),
  ...(card.kw?.length ? { kw: card.kw } : {}), ...(card.type === "unit" ? { role: roleOfCard(card) } : {}),
  ...(card.gear ? { gear: { atk: card.gear.atk, hp: card.gear.hp } } : {}),
  text: card.text, flavour: card.flavour, ...(card.token ? { token: true } : {})
}));
const lines = rows.map((row) => `  ${JSON.stringify(row)}`).join(",\n");
const out = [
  "// Generated by mobile/scripts/gen-clash-cards.ts from src/services/tcg-cards-set1.ts. Do not edit by hand.",
  'import type { ClashCard } from "./types";',
  "",
  "export const SET1: readonly ClashCard[] = [",
  lines,
  "];",
  ""
].join("\n");
writeFileSync(new URL("../src/clash/set1.ts", import.meta.url), out);
console.log(`wrote ${rows.length} cards`);

// The French wording of the same ids (src/services/tcg-cards-set1-fr.ts), drawn when the app language is French.
const fr = Object.entries(CARDS_SET1_FR).map(([id, card]) => `  ${JSON.stringify(id)}: ${JSON.stringify(card)}`).join(",\n");
writeFileSync(new URL("../src/clash/set1-fr.ts", import.meta.url), [
  "// Generated by mobile/scripts/gen-clash-cards.ts from src/services/tcg-cards-set1-fr.ts. Do not edit by hand.",
  "",
  "export interface CardFr { name: string; text: string; flavour: string }",
  "export const SET1_FR: Readonly<Record<string, CardFr>> = {",
  fr,
  "};",
  ""
].join("\n"));
console.log(`wrote ${Object.keys(CARDS_SET1_FR).length} French cards`);
