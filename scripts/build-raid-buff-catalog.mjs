import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BUFF_CATALOGS } from "../companion/raid-buffs.mjs";
function lua(value) {
  if (typeof value === "boolean") return String(value);
  if (typeof value === "number") return String(value);
  if (typeof value === "string") return '"' + [...Buffer.from(value)].map(byte => byte > 126 || byte < 32 ? "\\" + String(byte).padStart(3, "0") : byte === 34 || byte === 92 ? "\\" + String.fromCharCode(byte) : String.fromCharCode(byte)).join("") + '"';
  return "{" + Object.entries(value).map(([key, item]) => `[${Array.isArray(value) ? Number(key) + 1 : lua(key)}]=${lua(item)}`).join(",") + "}";
}
export function renderBuffCatalog() { return "-- Generated by scripts/build-raid-buff-catalog.mjs; edit companion/raid-buffs.mjs.\nlocal addonName, ns = ...\nns.raidBuffCatalogs = " + lua(BUFF_CATALOGS) + "\n"; }
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const path = "addon/Guilded/Modules/RaidBuffCatalog.lua";
  if (process.argv.includes("--check")) { if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== renderBuffCatalog()) throw new Error("Raid buff catalog is out of sync."); }
  else writeFileSync(path, renderBuffCatalog());
}
